#!/usr/bin/env node
// Keeps the "Latest guides" block on the homepage in step with the insights feed.
//
//   node scripts/patch-homepage-insights.mjs          # patch / refresh
//   node scripts/patch-homepage-insights.mjs --check  # fail if the block is missing or stale
//
// Why this exists: measured 2026-09-14, index.html linked only four insights
// articles — all four published April 2026 — from inside body copy. The eleven
// articles written since (the whole HDB financing cluster, the 2027 mega-launch
// piece, the EC guide) had no homepage link at all, and Search Console knew of
// just 4 internal links for a 116-page site. The homepage is the most-crawled
// page on the domain, so anything it does not link is slow to be discovered.
//
// Reads insights/feed.json rather than the articles so the block cannot drift
// from the feed, which tests/insights-feed-integrity.test.mjs already pins to
// the article titles.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = path.join(ROOT, 'index.html');
const FEED = path.join(ROOT, 'insights', 'feed.json');
const APEX = 'https://joetay.com';
const checkOnly = process.argv.includes('--check');

export const HOMEPAGE_INSIGHTS_MARKER = 'data-jt-homepage-insights';
const COUNT = 6;

const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Newest-first, de-duplicated by URL, trimmed to COUNT. */
function latestItems() {
  const feed = JSON.parse(fs.readFileSync(FEED, 'utf8'));
  const seen = new Set();
  return feed.items
    .filter((item) => {
      if (!item.url || !item.url.startsWith(`${APEX}/insights/`) || seen.has(item.url)) return false;
      seen.add(item.url);
      return true;
    })
    .sort((a, b) => String(b.date_published).localeCompare(String(a.date_published)))
    .slice(0, COUNT);
}

/** "2026-09-14T00:00:00+08:00" -> "Sep 2026" */
function monthLabel(value) {
  const date = new Date(value);
  return Number.isNaN(date.getTime())
    ? ''
    : date.toLocaleDateString('en-SG', { month: 'short', year: 'numeric', timeZone: 'Asia/Singapore' });
}

export function homepageInsightsHtml() {
  const cards = latestItems()
    .map((item) => {
      const href = item.url.slice(APEX.length);
      const when = monthLabel(item.date_published);
      // The summary is a full sentence in the feed; one line is enough on a card.
      const summary = String(item.summary || '').split(/(?<=\.)\s/)[0];
      return `      <a class="jt-hi-card" href="${esc(href)}">
        <span class="jt-hi-date">${esc(when)}</span>
        <strong class="jt-hi-title">${esc(item.title)}</strong>
        <span class="jt-hi-summary">${esc(summary)}</span>
      </a>`;
    })
    .join('\n');

  return `<!-- Latest guides — generated by scripts/patch-homepage-insights.mjs -->
<section class="section jt-hi" id="latest-guides" ${HOMEPAGE_INSIGHTS_MARKER} aria-labelledby="latest-guides-title">
  <div class="jt-hi-inner">
    <p class="jt-hi-eyebrow">Written by Joe</p>
    <h2 id="latest-guides-title" class="reveal">Read this before you decide.</h2>
    <p class="jt-hi-lede">Plain-English guides on the questions Singapore sellers, buyers and landlords actually ask — each one rebuilt from HDB, URA and CPF sources rather than opinion.</p>
    <div class="jt-hi-grid">
${cards}
    </div>
    <p class="jt-hi-more"><a href="/insights/">Browse all guides &rarr;</a> &middot; <a href="/zh/insights/hdb-valuation-explained.html" lang="zh-Hans" hreflang="zh-Hans">中文指南</a></p>
  </div>
</section>
<style>
/* Colours are inherited or currentColor-derived so the block follows the
   site theme toggle in both directions without a second palette. */
.jt-hi{padding:64px 24px}
.jt-hi-inner{max-width:1080px;margin:0 auto}
.jt-hi-eyebrow{font-size:.74rem;letter-spacing:.12em;text-transform:uppercase;font-weight:700;margin:0 0 8px;color:var(--emerald-aa,#047857)}
.jt-hi h2{margin:0 0 10px}
.jt-hi-lede{margin:0 0 28px;max-width:62ch;opacity:.85}
.jt-hi-grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(260px,1fr));gap:18px}
.jt-hi-card{display:flex;flex-direction:column;gap:7px;padding:20px;border:1px solid rgba(127,127,127,.26);border-radius:12px;text-decoration:none;color:inherit;background:rgba(127,127,127,.04);transition:border-color .2s,transform .2s}
.jt-hi-card:hover{border-color:var(--emerald-aa,#047857);transform:translateY(-2px)}
.jt-hi-card:hover .jt-hi-title{text-decoration:underline}
.jt-hi-date{font-size:.72rem;letter-spacing:.08em;text-transform:uppercase;font-weight:700;opacity:.7}
.jt-hi-title{font-size:1.03rem;line-height:1.35}
.jt-hi-summary{font-size:.9rem;line-height:1.55;opacity:.8}
.jt-hi-more{margin:24px 0 0;font-size:.94rem}
.jt-hi-more a{font-weight:700}
@media(max-width:600px){.jt-hi{padding:44px 20px}.jt-hi-grid{gap:14px}}
</style>
`;
}

// The block, from its opening comment through the closing </style>. Anchored on
// the marker so a hand-edit inside the section cannot make the regex miss it.
const blockRe = new RegExp(
  `<!-- Latest guides[^\\n]*-->\\n<section[^>]*${HOMEPAGE_INSIGHTS_MARKER}[^>]*>[\\s\\S]*?</section>\\n<style>[\\s\\S]*?</style>\\n`,
);

const html = fs.readFileSync(PAGE, 'utf8');
const fresh = homepageInsightsHtml();
const had = blockRe.test(html);

let patched;
if (had) {
  patched = html.replace(blockRe, fresh);
} else {
  const anchor = '<!-- Final CTA -->';
  if (!html.includes(anchor)) {
    console.error(`::error file=index.html::no "${anchor}" anchor to insert the latest-guides block before`);
    process.exit(1);
  }
  patched = html.replace(anchor, `${fresh}${anchor}`);
}

if (patched === html) {
  if (!checkOnly) console.log('Homepage latest-guides block: already current');
  process.exit(0);
}

if (checkOnly) {
  console.error(
    `::error file=index.html::homepage latest-guides block is ${had ? 'stale' : 'missing'} — run: node scripts/patch-homepage-insights.mjs`,
  );
  process.exit(1);
}

fs.writeFileSync(PAGE, patched);
console.log(`Homepage latest-guides block: ${had ? 'refreshed' : 'inserted'} (${COUNT} newest articles)`);
